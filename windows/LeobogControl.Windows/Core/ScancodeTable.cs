namespace LeobogControl.Core;

/// HID usage ↔ PS/2 Set 1 스캔코드 (Windows 의 kbdhid 변환표와 Scancode Map 레지스트리가 쓰는 값).
/// 확장 키는 0xE0xx. Pause(0x48, E1 1D 45) 처럼 Scancode Map 으로 표현할 수 없는 키는 표에 없다.
public static class ScancodeTable
{
    static readonly Dictionary<HidUsage, ushort> ToScan = Build();
    static readonly Dictionary<ushort, HidUsage> ToUsage = ToScan.GroupBy(k => k.Value).ToDictionary(g => g.Key, g => g.First().Key);

    static Dictionary<HidUsage, ushort> Build()
    {
        var d = new Dictionary<HidUsage, ushort>();
        void K(uint usage, ushort sc) => d[HidUsage.Keyboard(usage)] = sc;
        void C(uint usage, ushort sc) => d[HidUsage.Consumer(usage)] = sc;
        // 문자 (A–Z)
        ushort[] letters = { 0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, 0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C };
        for (uint i = 0; i < 26; i++) K(0x04 + i, letters[i]);
        // 숫자 1–9, 0
        for (uint i = 0; i < 9; i++) K(0x1E + i, (ushort)(0x02 + i));
        K(0x27, 0x0B);
        K(0x28, 0x1C); K(0x29, 0x01); K(0x2A, 0x0E); K(0x2B, 0x0F); K(0x2C, 0x39);
        K(0x2D, 0x0C); K(0x2E, 0x0D); K(0x2F, 0x1A); K(0x30, 0x1B); K(0x31, 0x2B); K(0x32, 0x2B);  // 0x31/0x32 → 같은 0x2B (역변환은 먼저 등록된 0x31)
        K(0x33, 0x27); K(0x34, 0x28); K(0x35, 0x29); K(0x36, 0x33); K(0x37, 0x34); K(0x38, 0x35); K(0x39, 0x3A);
        for (uint i = 0; i < 10; i++) K(0x3A + i, (ushort)(0x3B + i));   // F1–F10
        K(0x44, 0x57); K(0x45, 0x58);                                      // F11, F12
        K(0x46, 0xE037); K(0x47, 0x46);                                    // PrintScreen, ScrollLock
        K(0x49, 0xE052); K(0x4A, 0xE047); K(0x4B, 0xE049); K(0x4C, 0xE053); K(0x4D, 0xE04F); K(0x4E, 0xE051);
        K(0x4F, 0xE04D); K(0x50, 0xE04B); K(0x51, 0xE050); K(0x52, 0xE048);
        K(0x53, 0x45); K(0x54, 0xE035); K(0x55, 0x37); K(0x56, 0x4A); K(0x57, 0x4E); K(0x58, 0xE01C);
        ushort[] kp = { 0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49, 0x52 };  // KP1–KP9, KP0
        for (uint i = 0; i < 10; i++) K(0x59 + i, kp[i]);
        K(0x63, 0x53); K(0x64, 0x56); K(0x65, 0xE05D); K(0x66, 0xE05E); K(0x67, 0x59);
        ushort[] f13 = { 0x64, 0x65, 0x66, 0x67, 0x68, 0x69, 0x6A, 0x6B, 0x6C, 0x6D, 0x6E, 0x76 };
        for (uint i = 0; i < 12; i++) K(0x68 + i, f13[i]);               // F13–F24
        K(0x87, 0x73); K(0x88, 0x70); K(0x89, 0x7D); K(0x8A, 0x79); K(0x8B, 0x7B); K(0x8C, 0x5C);  // International1–6
        K(0x90, 0x72); K(0x91, 0x71);                                      // 한/영, 한자
        K(0xE0, 0x1D); K(0xE1, 0x2A); K(0xE2, 0x38); K(0xE3, 0xE05B);
        K(0xE4, 0xE01D); K(0xE5, 0x36); K(0xE6, 0xE038); K(0xE7, 0xE05C);
        // 소비자(미디어) 페이지 — kbdhid 가 E0 확장 스캔코드로 변환하는 것들
        C(0xB5, 0xE019); C(0xB6, 0xE010); C(0xB7, 0xE024); C(0xCD, 0xE022);
        C(0xE2, 0xE020); C(0xE9, 0xE030); C(0xEA, 0xE02E);
        C(0x183, 0xE06D); C(0x18A, 0xE06C); C(0x192, 0xE021); C(0x194, 0xE06B);
        C(0x221, 0xE065); C(0x223, 0xE032); C(0x224, 0xE06A); C(0x225, 0xE069); C(0x226, 0xE068); C(0x227, 0xE067); C(0x22A, 0xE066);
        C(0x30, 0xE05E);  // Power
        C(0x32, 0xE05F);  // Sleep
        return d;
    }

    /// Scancode Map 으로 표현 가능한가 (원본/대상 모두). 비활성화(0x07:0x00) 는 대상으로만 가능.
    public static bool CanExpress(HidUsage u) => u == HidUsage.Disabled || ToScan.ContainsKey(u);
    public static ushort? Scancode(HidUsage u) => u == HidUsage.Disabled ? (ushort)0 : ToScan.TryGetValue(u, out var s) ? s : null;
    public static HidUsage? Usage(ushort scancode) => ToUsage.TryGetValue(scancode, out var u) ? u : null;
    public static string ScanText(ushort sc) => sc >= 0x100 ? $"E0 {sc & 0xFF:X2}" : $"{sc:X2}";
}
